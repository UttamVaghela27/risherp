package com.risherp.dto.settings;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.*;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class InvoiceSettingsDto {

    @NotBlank(message = "Invoice title is required")
    @Size(max = 100, message = "Invoice title must not exceed 100 characters")
    @Builder.Default
    private String invoiceTitle = "TAX INVOICE";

    @Size(max = 255, message = "Invoice footer must not exceed 255 characters")
    @Builder.Default
    private String invoiceFooter = "Generated by RISHERP Enterprise Billing";

    @Builder.Default
    private Boolean showBusinessLogo = true;

    @Builder.Default
    private Boolean showBusinessAddress = true;

    @Builder.Default
    private Boolean showCustomerMobile = true;

    @Builder.Default
    private Boolean showCustomerAddress = true;

    @Builder.Default
    private Boolean showPaymentMode = true;

    @Builder.Default
    private Boolean showNotes = true;

    @Builder.Default
    private Boolean showTerms = true;

    private String defaultInvoiceNotes;

    private String defaultInvoiceTerms;
}
