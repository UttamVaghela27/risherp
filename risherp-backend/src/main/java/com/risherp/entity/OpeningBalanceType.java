package com.risherp.entity;

/**
 * OpeningBalanceType Enum
 * Defines the direction of the opening balance.
 * RECEIVABLE: Customer owes money to the business.
 * PAYABLE: Business owes money to the supplier.
 * NONE: Zero opening balance.
 */
public enum OpeningBalanceType {
    RECEIVABLE,
    PAYABLE,
    NONE
}
