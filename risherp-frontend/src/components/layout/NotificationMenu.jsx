import { useState } from 'react';
import {
  IconButton,
  Badge,
  Menu,
  MenuItem,
  Typography,
  Box,
  Divider,
  Button,
  ListItemIcon,
} from '@mui/material';
import NotificationsNoneOutlinedIcon from '@mui/icons-material/NotificationsNoneOutlined';
import WarningAmberOutlinedIcon from '@mui/icons-material/WarningAmberOutlined';
import ReceiptLongOutlinedIcon from '@mui/icons-material/ReceiptLongOutlined';
import PaymentOutlinedIcon from '@mui/icons-material/PaymentOutlined';

const initialNotifications = [
  {
    id: 1,
    title: 'Low Stock Alert',
    description: 'Item "HP LaserJet Toner 88A" below minimum stock (2 remaining).',
    time: '10m ago',
    type: 'warning',
    icon: <WarningAmberOutlinedIcon fontSize="small" sx={{ color: 'warning.main' }} />,
    unread: true,
  },
  {
    id: 2,
    title: 'Payment Received',
    description: 'Received ₹18,500 from Metro Enterprises via UPI.',
    time: '45m ago',
    type: 'success',
    icon: <PaymentOutlinedIcon fontSize="small" sx={{ color: 'success.main' }} />,
    unread: true,
  },
  {
    id: 3,
    title: 'Recent Sale Invoice',
    description: 'Invoice #INV-2026-089 generated by Amit Shah.',
    time: '2h ago',
    type: 'info',
    icon: <ReceiptLongOutlinedIcon fontSize="small" sx={{ color: 'info.main' }} />,
    unread: true,
  },
];

/**
 * NotificationMenu Component
 * TopNavbar notification bell with interactive dropdown.
 */
const NotificationMenu = () => {
  const [anchorEl, setAnchorEl] = useState(null);
  const [notifications, setNotifications] = useState(initialNotifications);

  const unreadCount = notifications.filter((n) => n.unread).length;

  const handleOpen = (e) => setAnchorEl(e.currentTarget);
  const handleClose = () => setAnchorEl(null);

  const handleMarkAllRead = () => {
    setNotifications((prev) => prev.map((n) => ({ ...n, unread: false })));
  };

  return (
    <>
      <IconButton
        size="small"
        onClick={handleOpen}
        aria-label="notifications"
        sx={{
          color: 'text.secondary',
          '&:hover': { bgcolor: 'background.default', color: 'primary.main' },
        }}
      >
        <Badge badgeContent={unreadCount} color="error" variant={unreadCount > 0 ? 'standard' : 'dot'}>
          <NotificationsNoneOutlinedIcon sx={{ fontSize: 22 }} />
        </Badge>
      </IconButton>

      <Menu
        anchorEl={anchorEl}
        open={Boolean(anchorEl)}
        onClose={handleClose}
        PaperProps={{
          elevation: 3,
          sx: {
            width: 340,
            maxHeight: 420,
            borderRadius: 2.5,
            border: 1, borderColor: 'divider',
            mt: 1,
            overflow: 'hidden',
          },
        }}
        transformOrigin={{ horizontal: 'right', vertical: 'top' }}
        anchorOrigin={{ horizontal: 'right', vertical: 'bottom' }}
      >
        <Box sx={{ px: 2, py: 1.5, display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
          <Typography variant="subtitle2" fontWeight={700}>
            Notifications
          </Typography>
          {unreadCount > 0 && (
            <Button
              size="small"
              onClick={handleMarkAllRead}
              sx={{ fontSize: '0.75rem', p: 0, minWidth: 'auto', textTransform: 'none' }}
            >
              Mark all as read
            </Button>
          )}
        </Box>
        <Divider />

        {notifications.length === 0 ? (
          <Box sx={{ p: 3, textAlign: 'center' }}>
            <Typography variant="caption" color="text.secondary">
              No new notifications
            </Typography>
          </Box>
        ) : (
          notifications.map((item) => (
            <MenuItem
              key={item.id}
              onClick={handleClose}
              sx={{
                py: 1.25,
                px: 2,
                borderBottom: '1px solid #f8fafc',
                bgcolor: item.unread ? 'rgba(30, 58, 138, 0.03)' : 'transparent',
                display: 'flex',
                alignItems: 'flex-start',
                gap: 1.5,
              }}
            >
              <ListItemIcon sx={{ minWidth: 'auto', mt: 0.25 }}>
                {item.icon}
              </ListItemIcon>
              <Box sx={{ flex: 1, overflow: 'hidden' }}>
                <Box sx={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
                  <Typography variant="caption" fontWeight={700} color="text.primary">
                    {item.title}
                  </Typography>
                  <Typography variant="caption" color="text.disabled" sx={{ fontSize: '0.7rem' }}>
                    {item.time}
                  </Typography>
                </Box>
                <Typography
                  variant="caption"
                  color="text.secondary"
                  sx={{
                    display: '-webkit-box',
                    WebkitLineClamp: 2,
                    WebkitBoxOrient: 'vertical',
                    overflow: 'hidden',
                    lineHeight: 1.3,
                    mt: 0.25,
                  }}
                >
                  {item.description}
                </Typography>
              </Box>
            </MenuItem>
          ))
        )}
      </Menu>
    </>
  );
};

export default NotificationMenu;
